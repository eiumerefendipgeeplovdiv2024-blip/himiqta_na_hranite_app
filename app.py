# Инициализиране на EasyOCR четеца (за български и английски език)
@st.cache_resource
def load_ocr():
    return easyocr.Reader(['bg', 'en'])

reader = load_ocr()

# Заглавие на приложението
st.title("🔍 Скенер на съставки & Анализ на здравето")
st.write("Качете снимка на етикета или използвайте камерата си, за да разберете какво съдържа Вашият продукт.")

# 2. Опция за избор между файл и камера
source_option = st.radio("Изберете метод на заснемане:", ("Качване на снимка", "Използване на камера"))

image = None

if source_option == "Качване на снимка":
    uploaded_file = st.file_uploader("Изберете изображение...", type=["jpg", "jpeg", "png"])
    if uploaded_file is not None:
        image = Image.open(uploaded_file)
        st.image(image, caption="Качена снимка", use_container_width=True)

else:
    camera_file = st.camera_input("Снимайте етикета със съставките")
    if camera_file is not None:
        image = Image.open(camera_file)

# 3. Обработка на изображението и OCR
if image is not None:
    st.info("Обработка на изображението... Моля, изчакайте.")
    
    # Превръщане на PIL изображението в numpy масив за EasyOCR
    image_np = np.array(image)
    
    # Разчитане на текста
    results = reader.readtext(image_np, detail=0)
    full_text = " ".join(results).lower()
    
    st.subheader("Разчетен текст от етикета:")
    st.write(full_text if full_text else "Не беше открит текст. Опитайте с по-чиста снимка.")
    
    # 4. Анализ и търсене на съставки в нашата база данни
    found_ingredients = []
    
    for ing_name, ing_data in INGREDIENTS_DB.items():
        if ing_name in full_text:
            found_ingredients.append({
                "Съставка": ing_name.capitalize(),
                "Статус": ing_data["status"]
            })
            
    # 5. Показване на резултатите
    if found_ingredients:
        st.subheader("📊 Анализ на съставките")
        
        # Разделяне на съставките по категории за визуализация
        for ing in found_ingredients:
            name = ing["Съставка"]
            status = ing["Статус"]
            db_entry = INGREDIENTS_DB[name.lower()]
            
            # Цветово кодиране според вредността
            if status == "Полезна":
                color = "🟢"
            elif status == "Невредна":
                color = "🟡"
            else:
                color = "🔴"
                
            # Интерактивен бутон/експандер за всяка съставка
            with st.expander(f"{color} {name} — ({status})"):
                st.markdown(f"**ℹ️ Какво представлява:** {db_entry['info']}")
                st.markdown(f"**⚠️ Дългосрочни ефекти:** {db_entry['long_term']}")
    else:
        if full_text:
            st.warning("Открит е текст, но съставките не съвпадат с нашата база данни. Опитайте да добавите съставки като 'захар', 'вода' или 'палмово масло' за тест.")
