# Опция за избор на метод за въвеждане
source_option = st.radio("Изберете метод:", ("Качване на снимка", "Снимане с камера"))

image = None

if source_option == "Качване на снимка":
    uploaded_file = st.file_uploader("Изберете изображение...", type=["jpg", "jpeg", "png"])
    if uploaded_file is not None:
        image = Image.open(uploaded_file)
else:
    camera_file = st.camera_input("Снимайте етикета")
    if camera_file is not None:
        image = Image.open(camera_file)

if image is not None:
    st.image(image, caption='Въведено изображение', use_container_width=True)
    
    with st.spinner('Обработка на текста и разпознаване...'):
        # Конвертиране на PIL Image в numpy array за EasyOCR
        img_np = np.array(image)
        results = reader.readtext(img_np)
        
        # Събиране на целия разпознат текст
        detected_text = " ".join([text[1].lower() for text in results])
        
    st.subheader("🤖 Намерен текст:")
    with st.expander("Виж суровия разпознат текст"):
        st.write(detected_text)

    # Анализ и сортиране на съставките
    found_ingredients = []

    for category, ingredients_dict in INGREDIENTS_DB.items():
        for name, description in ingredients_dict.items():
            if name in detected_text:
                found_ingredients.append({
                    "Съставка": name.capitalize(),
                    "Категория": category.capitalize(),
                    "Описание": description
                })

    st.subheader("📊 Анализ на съставките")

    if found_ingredients:
        df = pd.DataFrame(found_ingredients)
        
        # Сортиране по категория за по-добра прегледност (Полезни -> Безвредни -> Вредни)
        category_order = {"Полезни": 0, "Безвредни": 1, "Вредни": 2}
        df['Order'] = df['Категория'].map(category_order)
        df = df.sort_values('Order').drop('Order', axis=1).reset_index(drop=True)
        
        # Показване на основната таблица (без детайлното описание в нея)
        st.dataframe(df[["Съставка", "Категория"]], use_container_width=True)
        
        # Интерактивна секция за кликане/избор на допълнителна информация
        st.markdown("### 🔍 Кликнете върху съставка за детайли и дългосрочни ефекти:")
        selected_ingredient = st.selectbox("Изберете съставка от списъка:", df["Съставка"].unique())
        
        if selected_ingredient:
            # Намиране на описанието за избраната съставка
            info = df[df["Съставка"] == selected_ingredient].iloc[0]
            
            # Цветово кодиране на категорията за визуален акцент
            if info['Категория'] == 'Вредни':
                st.error(f"🔴 **{info['Съставка']} ({info['Категория']}):** {info['Описание']}")
            elif info['Категория'] == 'Полезни':
                st.success(f"🟢 **{info['Съставка']} ({info['Категория']}):** {info['Описание']}")
            else:
                st.info(f"🔵 **{info['Съставка']} ({info['Категория']}):** {info['Описание']}")
    else:
        st.warning("Не бяха намерени познати съставки от базата данни в този текст. Опитайте с по-ясна снимка или проверете дали съставките присъстват в примерния списък.")

else:
    st.info("Моля, качете снимка или използвайте камерата, за да започнете анализа.")
