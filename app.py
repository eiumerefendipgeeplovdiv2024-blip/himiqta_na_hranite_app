# Инициализиране на OCR четеца (зарежда се веднъж)
@st.cache_resource
def load_ocr():
    return easyocr.Reader(['bg', 'en'])

reader = load_ocr()

# --- ИНТЕРФЕЙС НА ПРИЛОЖЕНИЕТО ---
st.set_page_config(page_title="FoodScanner AI", page_icon="🥗")

st.title("🔍 Скенер за Хранителни Етикети")
st.markdown("Качете снимка на етикета на продукта, за да разберете какво съдържа.")

# Качване на файл
uploaded_file = st.file_uploader("Изберете снимка на етикет...", type=["jpg", "jpeg", "png"])

if uploaded_file is not None:
    # Показване на изображението
    image = Image.open(uploaded_file)
    st.image(image, caption='Качен етикет', use_column_width=True)
    
    with st.spinner('Анализиране на съставките...'):
        # Конвертиране за OCR
        img_array = np.array(image)
        results = reader.readtext(img_array)
        detected_text = " ".join([res[1].upper() for res in results])
        
        st.subheader("Резултати от анализа:")
        
        found_any = False
        # Проверка за вредни съставки
        for code, data in INGREDIENTS_DB.items():
            if code in detected_text:
                found_any = True
                with st.expander(f"🔴 Намерено: {code} - {data['име']}"):
                    st.markdown(f"**Тип:** {data['тип']}")
                    st.markdown(f"**Ниво на риск:** <span style='color:{data['цвят']}'>{data['ниво']}</span>", unsafe_allow_all_html=True)
                    st.markdown(f"**Здравословни проблеми:** {data['рискове']}")
        
        if not found_any:
            st.success("Не бяха открити опасни Е-номера от нашата база данни. Проверявайте винаги и за добавена захар!")

# --- СЕКЦИЯ ЗА АЛТЕРНАТИВИ ---
